"""会话级权限判定：宿主与各模块共用的**唯一**一份实现。

为什么要有这个文件（而不是让每个模块自己写一份）
--------------------------------------------------

权限规则一旦出现两份副本，**改模型就会漏改一处，那就是一个安全洞**。
`modules/recruit` 落地时如实报告了这个重复，总监裁决收敛到此处。

纯逻辑：**不 import astrbot**（`ruff` 的 TID 禁入会拦），因此只接收布尔入参、
不接收 event。判断「是否群聊」「是否管理员」仍然由调用方（装配层）从事件上取——
那些是真的框架知识，不该渗进 core。

规则（为什么不长这样，见 `docs/implementation/implementation.md` §2.6 的裁决）
-----------------------------------------------------------------------------

- **私聊无条件放行**：私聊里绑定只影响发起者自己，没有可被滥用的面。
  旧模型「只允许已绑定的那个会话」会造成改绑死锁——绑了 A 就再也换不到 B，
  A 那个号一旦掉线功能永久锁死（服务器上已实证）。
- **群聊仅限 AstrBot 管理员**：群里发指令会把结果发给所有人，可能打扰他人。
  **这才是真正需要防的对象。**
"""

from __future__ import annotations

__all__ = ["session_allowed"]


def session_allowed(*, is_group: bool, is_admin: bool, action: str) -> tuple[bool, str]:
    """判定某个操作是否允许在此会话执行。

    Args:
        is_group: 事件是否来自群聊。
        is_admin: 发起者是否 AstrBot 管理员（`AstrMessageEvent.is_admin()`）。
        action: 这个模块要做的事的**人话说法**，例如「操作换班提醒」「查公开招募」。
            用于拼出具体的拒绝理由——不同的模块做不同的事，统一成一句空泛的
            「权限不足」对用户毫无帮助。

    Returns:
        `(是否允许, 拒绝原因)`；允许时原因恒为空字符串。
    """
    if not is_group or is_admin:
        return True, ""
    return False, (
        f"群聊里只有 AstrBot 管理员能{action}：在群里发指令会把结果发给所有人，"
        "可能打扰其他成员。想自己用，请私聊我发同一条指令——私聊不需要管理员。"
    )
